export interface ProviderPreset {
  id: string;
  name: string;
  kind: UpstreamKind;
  adapter: 'openai-http' | 'cli-spawn';
  plugin_id: string | null;
  auth_mode: AuthMode;
  base_url: string | null;
  reset_mode: 'none' | 'cookie_reset';
  cost_per_1k: number;
  /** What the setup wizard says this provider needs before it can answer. */
  credential_hint: string;
  models: string[];
  tools_mode: ToolsMode;
  cli_command?: string;
  note?: string;
}

